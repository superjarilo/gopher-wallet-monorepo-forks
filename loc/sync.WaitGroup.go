package main

/**
 * 	Задача https://go.dev/play/p/K3LXhpZfetY (sync.WaitGroup и ловушки конкурентности)
 *	Нужно одновременно (параллельно) запустить обработку 5 транзакций кошельков,
 * 	дождаться выполнения всех 5 операций и только после этого вывести финальный лог.
 */

import (
	"fmt"
	"sync"
	"time"
)

func processTransaction(id int, wg *sync.WaitGroup) {
	// ВАЖНО: defer wg.Done() уменьшает счетчик WaitGroup на 1 при выходе из функции.
	// Если забыть вызвать Done, основная горутина зависнет в состоянии дедлока (deadlock)!
	defer wg.Done()

	fmt.Printf("[START] Обработка транзакции #%d\n", id)
	time.Sleep(200 * time.Millisecond) // Имитируем работу с базой
	fmt.Printf("[END] Транзакция #%d успешно обработана\n", id)
}

func main() {
	var wg sync.WaitGroup

	for i := 1; i <= 5; i++ {
		// ВАЖНО 1: wg.Add(1) увеличивает счетчик ожидаемых горутин.
		// Всегда вызывай Add() в ОРИГИНАЛЬНОЙ горутине ДО запуска `go ...`.
		// Если вызвать внутри горутины, `wg.Wait()` может сработать раньше, чем горутина успеет запуститься.
		wg.Add(1)

		// ВАЖНО 2: Передача переменной цикла. Начиная с Go 1.22, переменная 'i'
		// создается заново на каждой итерации, поэтому ее можно безопасно использовать.
		// Но хорошей практикой (и правилом хорошего тона на собеседованиях) остается
		// явная передача аргумента в функцию или замыкание, чтобы избежать путаницы.
		go processTransaction(i, &wg)
		// ВАЖНО 3: Передавать WaitGroup в функцию нужно СТРОГО по указателю (*sync.WaitGroup).
		// Если передать по значению, Go скопирует структуру, счетчик оригинального wg не изменится,
		// и мы снова получим вечный deadlock в главном потоке.
	}

	fmt.Println("Главный поток: жду завершения всех транзакций...")

	// Блокируем главный поток, пока счетчик WaitGroup не станет равен 0
	wg.Wait()

	fmt.Println("Главный поток: все транзакции выполнены успешно!")
}
